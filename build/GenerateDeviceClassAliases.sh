#!/bin/sh

set -e

# Regenerates build/device-class-aliases/ from the xcframeworks in ../libs/.
#
# Why this exists: dd-sdk-ios ships its prebuilt device slices with a 12.0 deployment target
# while the simulator slices are built at 14.0 (the arm64-simulator floor). Below iOS 13 the
# Swift compiler does not emit a statically-registered Objective-C class - no
# `_OBJC_CLASS_$_<Name>` symbol, no `__objc_classlist` entry - for @objc classes whose metadata
# needs runtime fix-ups. The class object itself is still there, and still exported, under its
# Swift metadata symbol (`_$s...CN`); only the Objective-C-name spelling of it is withheld. The
# static registrar in consuming apps references exactly that spelling, so a device link fails on
# symbols the simulator link resolves fine - 41 classes across five frameworks as of 3.14.0.
#
# The repair has two halves, and this script generates both:
#
#   1. <Framework>.aliases - one linker flag per class:
#
#        -Wl,-alias,<swift metadata symbol>,_OBJC_CLASS_$_<Name>
#
#      which makes the app's reference an indirect symbol for the metadata export - the same
#      address the simulator slice exports under both names. Datadog.Binding.props folds the
#      file into the framework's NativeReference LinkerFlags.
#
#   2. <Framework>Realize.xcframework - a static library with one dyld initializer
#      (__attribute__((constructor))) that calls each aliased class's Swift metadata accessor
#      (`_$s...CMa`). The metadata the aliases point at starts out *unrealized* on device, and
#      messaging it in that state is a segfault, not a slow path. It must be realized before
#      main() runs: the static registrar's xamarin_create_classes - called from main, before
#      any managed code - does `[DDConfiguration class]` for every mapped bound class, so a
#      managed module initializer is already too late (all verified on hardware). A dyld
#      initializer in the app image runs after the Datadog dylibs are loaded and before main,
#      which is exactly the window. The generated source sits next to the archive for review.
#
# The name mapping is derived, not guessed: in the simulator slice `_OBJC_CLASS_$_<Name>` and
# `_$s...CN` are two names for the same address, so joining on the address gives the Swift
# symbol for each Objective-C name. The script then requires that symbol to be exported by the
# device slice before writing an alias.
#
# Run it after every FetchXcFrameworks.sh, and commit the result. If upstream fixes its release
# pipeline (the device slices gain the class symbols), the files simply come out empty and
# Datadog.Binding.props stops emitting anything. The PackageTests symbol audit fails the build
# if these files drift out of date with libs/.
#
# Usage:
#   ./GenerateDeviceClassAliases.sh

cd "$(dirname "$0")"

ROOT="$(cd .. && pwd)"
LIBS="$ROOT/libs"
OUT="$ROOT/build/device-class-aliases"

if [ ! -d "$LIBS" ]; then
    echo "error: $LIBS does not exist - run ./build/FetchXcFrameworks.sh first" >&2
    exit 1
fi

exec python3 - "$LIBS" "$OUT" <<'PYTHON'
import plistlib
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

libs = Path(sys.argv[1])
out = Path(sys.argv[2])
out.mkdir(parents=True, exist_ok=True)

CLASS_PREFIX = "_OBJC_CLASS_$_"
METADATA_RE = re.compile(r"^_\$s.*CN$")

failures = []
total = 0


def write_realizer(name, metadata_symbols):
    """Generates and builds <name>Realize.xcframework: a static library whose single dyld
    initializer realizes every aliased class via its Swift metadata accessor before main()."""
    externs = []
    calls = []
    for index, symbol in enumerate(sorted(metadata_symbols)):
        accessor = symbol[:-1] + "Ma"  # _$s...CN -> _$s...CMa
        externs.append(
            f'extern MetadataResponse Realize{index}(size_t) __asm("{accessor}");')
        calls.append(f"    Realize{index}(0);")

    source = out / f"{name}Realize.c"
    source.write_text(
        "// Generated by build/GenerateDeviceClassAliases.sh - do not edit.\n"
        "//\n"
        f"// Realizes the {len(calls)} classes {name}.aliases makes linkable, before main() and\n"
        "// therefore before the static registrar's xamarin_create_classes can message them -\n"
        "// unrealized Swift class metadata segfaults on the first message. See the script\n"
        "// header and build/device-class-aliases/README.md for the full story.\n"
        "#include <stddef.h>\n\n"
        "typedef struct { void *metadata; size_t state; } MetadataResponse;\n\n"
        + "\n".join(externs)
        + "\n\n__attribute__((constructor)) static void datadognet_realize_classes(void)\n{\n"
        + "\n".join(calls)
        + "\n}\n")

    xcframework = out / f"{name}Realize.xcframework"
    shutil.rmtree(xcframework, ignore_errors=True)
    with tempfile.TemporaryDirectory() as scratch:
        scratch = Path(scratch)
        archives = []
        slices = [
            ("device", "iphoneos", [("arm64-apple-ios12.0", "device-arm64")]),
            ("simulator", "iphonesimulator", [("arm64-apple-ios14.0-simulator", "sim-arm64"),
                                              ("x86_64-apple-ios14.0-simulator", "sim-x86_64")]),
        ]
        for label, sdk, targets in slices:
            sysroot = subprocess.run(
                ["xcrun", "--sdk", sdk, "--show-sdk-path"],
                check=True, capture_output=True, text=True).stdout.strip()
            thin = []
            for triple, stem in targets:
                obj = scratch / f"{stem}.o"
                subprocess.run(
                    ["xcrun", "clang", "-target", triple, "-isysroot", sysroot,
                     "-c", str(source), "-o", str(obj)],
                    check=True)
                archive = scratch / f"{stem}.a"
                subprocess.run(
                    ["xcrun", "libtool", "-static", "-no_warning_for_no_symbols",
                     "-o", str(archive), str(obj)],
                    check=True)
                thin.append(archive)
            fat = scratch / label / f"lib{name}Realize.a"
            fat.parent.mkdir()
            if len(thin) == 1:
                shutil.copy(thin[0], fat)
            else:
                subprocess.run(
                    ["xcrun", "lipo", "-create", *map(str, thin), "-o", str(fat)], check=True)
            archives.append(fat)
        command = ["xcodebuild", "-create-xcframework"]
        for archive in archives:
            command += ["-library", str(archive)]
        command += ["-output", str(xcframework)]
        subprocess.run(command, check=True, capture_output=True)


def slices(xcframework):
    """The (device, simulator) binary paths for the plain-iOS slices of an xcframework."""
    with (xcframework / "Info.plist").open("rb") as handle:
        plist = plistlib.load(handle)
    device = simulator = None
    for library in plist.get("AvailableLibraries", []):
        if library.get("SupportedPlatform") != "ios":
            continue
        variant = library.get("SupportedPlatformVariant")
        base = xcframework / library["LibraryIdentifier"]
        if "BinaryPath" in library:
            path = base / library["BinaryPath"]
        else:
            path = base / library["LibraryPath"]
            if path.suffix == ".framework":
                path = path / path.stem
        if variant is None:
            device = path
        elif variant == "simulator":
            simulator = path
    return device, simulator


def exported_symbols(binary):
    """{symbol name: address} of the defined external symbols of the arm64 slice."""
    result = subprocess.run(
        ["xcrun", "nm", "-arch", "arm64", "-gU", str(binary)],
        capture_output=True, text=True, check=True,
    )
    symbols = {}
    for line in result.stdout.splitlines():
        parts = line.split()
        if len(parts) == 3:
            symbols[parts[2]] = parts[0]
    return symbols


for xcframework in sorted(libs.glob("*.xcframework")):
    name = xcframework.stem
    device, simulator = slices(xcframework)
    if device is None or simulator is None:
        failures.append(f"{name}: could not identify both iOS slices in Info.plist")
        continue

    aliases_file = out / f"{name}.aliases"

    # A static archive (CrashReporting) is linked into the app wholesale, symbols and all, so
    # the missing-export problem cannot arise there. If it ever does, the address join below
    # would be meaningless across archive members anyway, so it is checked rather than assumed.
    is_archive = device.suffix == ".a"

    dev_symbols = exported_symbols(device)
    sim_symbols = exported_symbols(simulator)

    dev_classes = {s[len(CLASS_PREFIX):] for s in dev_symbols if s.startswith(CLASS_PREFIX)}
    sim_classes = {s[len(CLASS_PREFIX):] for s in sim_symbols if s.startswith(CLASS_PREFIX)}

    missing = sorted(sim_classes - dev_classes)
    extra = sorted(dev_classes - sim_classes)
    if extra:
        print(f"note: {name}: device slice exports classes the simulator slice does not: {', '.join(extra)}")

    if not missing:
        stale = [aliases_file, out / f"{name}Realize.c", out / f"{name}Realize.xcframework"]
        if any(path.exists() for path in stale):
            for path in stale:
                if path.is_dir():
                    shutil.rmtree(path)
                elif path.exists():
                    path.unlink()
            print(f"==> {name}: no missing classes any more - removed stale alias artifacts")
        else:
            print(f"==> {name}: no missing classes")
        continue

    if is_archive:
        failures.append(f"{name}: {len(missing)} classes missing from a static archive - aliasing cannot fix that")
        continue

    # Invert the simulator symbol table to find every name exported at a given address.
    by_address = {}
    for symbol, address in sim_symbols.items():
        by_address.setdefault(address, []).append(symbol)

    lines = []
    realized = []
    for cls in missing:
        address = sim_symbols[CLASS_PREFIX + cls]
        metadata = [s for s in by_address[address] if METADATA_RE.match(s)]
        if len(metadata) != 1:
            failures.append(
                f"{name}: {cls}: expected exactly one Swift metadata symbol at the class address, "
                f"found {metadata or 'none'}"
            )
            continue
        if metadata[0] not in dev_symbols:
            failures.append(
                f"{name}: {cls}: {metadata[0]} is not exported by the device slice - "
                f"nothing to alias this class to"
            )
            continue
        lines.append(f"-Wl,-alias,{metadata[0]},{CLASS_PREFIX}{cls}")
        realized.append(metadata[0])

    aliases_file.write_text("\n".join(lines) + "\n")
    write_realizer(name, realized)
    total += len(lines)
    print(f"==> {name}: {len(lines)} aliases + {name}Realize.xcframework written to build/device-class-aliases/")

print(f"==> {total} aliases in total")
if failures:
    print("", file=sys.stderr)
    for failure in failures:
        print(f"error: {failure}", file=sys.stderr)
    sys.exit(1)
PYTHON
